    html = ('<!doctype html><html lang="%s"><head><meta charset="utf-8"><title>%s</title>' % (lang, esc(title)) +
            ('<style>%s%s</style></head><body>%s%s</body></html>' % ('\n'.join(ff), css, ''.join(pages), chk)))
    os.makedirs(OUT, exist_ok=True)
    fn = os.path.join(OUT, 'report-%s-final%s.html' % (lang, '-check' if chk else ''))
    open(fn, 'w', encoding='utf-8').write(html)
    return fn


